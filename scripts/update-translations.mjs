// For each language, inject its extra keys right before its closing brace
for (const lang of ['en', 'hi', 'mr', 'bn', 'ta', 'te']) {
  const extraObj = EXTRA_KEYS[lang];
  const keysCode = Object.entries(extraObj)
    .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
    .join('\n');

  // Find the block for this language
  // Pattern: lang + ": {" ... "}"
  const langRegex = new RegExp(`(\\b${lang}:\\s*\\{[\\s\\S]*?)(    previous:\\s*['"][^'"]+['"]\\n  \\})`, 'm');
  
  if (langRegex.test(content)) {
    content = content.replace(langRegex, (match, prefix, suffix) => {
      // Suffix has "    previous: '...'\n  }"
      const prevLineMatch = suffix.match(/(    previous:\s*['"][^'"]+['"],?)\n  \}/);
      if (prevLineMatch) {
        return `${prefix}    previous: ${JSON.stringify(extraObj[lang === 'hi' ? 'previous' : 'previous'] || (lang==='en'?'Previous':lang==='hi'?'पीछे':lang==='mr'?'मागे':lang==='bn'?'পূর্ববর্তী':lang==='ta'?'முந்தைய':'మునుపటి'))},\n\n${keysCode}\n  }`;
      }
      return match;
    });
    console.log(`Updated language: ${lang}`);
  } else {
    console.warn(`Could not match regex for language: ${lang}`);
  }
}

fs.writeFileSync(filePath, content, 'utf-8');
